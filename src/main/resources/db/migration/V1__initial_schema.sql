-- Existing installations must explicitly baseline at version 0 after a backup
-- and schema review. No tables or user data are dropped by this migration.
CREATE TABLE IF NOT EXISTS hotels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    title varchar(255) NOT NULL,
    city varchar(255) NOT NULL,
    address varchar(255) NOT NULL,
    distance_from_city_center double precision NOT NULL,
    rating double precision DEFAULT 0,
    count_of_ratings integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    role varchar(255) NOT NULL CHECK (role IN ('ADMIN', 'USER'))
);
CREATE TABLE IF NOT EXISTS rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    description varchar(255) NOT NULL,
    number integer NOT NULL,
    price numeric(38,2) NOT NULL,
    room_capacity integer NOT NULL,
    hotel_id bigint NOT NULL REFERENCES hotels(id),
    UNIQUE (hotel_id, number)
);
CREATE TABLE IF NOT EXISTS bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    room_id bigint NOT NULL REFERENCES rooms(id),
    check_in_date date NOT NULL,
    check_out_date date NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bookings_room_dates
    ON bookings (room_id, check_in_date, check_out_date);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings (user_id);
